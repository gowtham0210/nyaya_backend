-- ---------------------------------------------------------------------------
-- Moves every identity past the highest id already in its table, so rows
-- copied in from MySQL with their original ids don't collide with new
-- inserts. Only ever moves a sequence forward, so it is safe to run on every
-- deploy (db:init does) - it never hands out the id of a deleted row again.
-- ---------------------------------------------------------------------------
DO $$
DECLARE
  col record;
  seq text;
  max_id bigint;
  last_id bigint;
BEGIN
  FOR col IN
    SELECT table_name, column_name
    FROM information_schema.columns
    WHERE table_schema = current_schema() AND is_identity = 'YES'
  LOOP
    seq := pg_get_serial_sequence(quote_ident(col.table_name), col.column_name);
    EXECUTE format('SELECT MAX(%I) FROM %I', col.column_name, col.table_name) INTO max_id;
    EXECUTE format('SELECT last_value FROM %s', seq) INTO last_id;

    IF max_id IS NOT NULL AND max_id >= last_id THEN
      PERFORM setval(seq, max_id, true);
    END IF;
  END LOOP;
END;
$$;
