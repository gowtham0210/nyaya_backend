-- Nyaya schema (PostgreSQL 14+). Applied by `npm run db:init`, which runs on
-- every deploy: every statement here is idempotent, so add new tables/columns
-- in that style (IF NOT EXISTS, CREATE OR REPLACE) or as a file under
-- ./migrations for changes that can't be (see src/scripts/migrate.js).
--
-- Converted from the former MySQL schema.sql plus all of its migrations, the
-- four help-resource tables seed-help-resources.js used to create, and
-- legal_updates (see the note on it).
--
-- Conversion choices, so the existing app code keeps its assumptions:
--   * AUTO_INCREMENT      -> GENERATED BY DEFAULT AS IDENTITY ("BY DEFAULT" so
--                            rows copied from MySQL can keep their ids; reset
--                            the identity after a data copy - see the end).
--   * UNSIGNED            -> dropped (no Postgres equivalent); non-id columns
--                            that relied on it get a CHECK (>= 0).
--   * TINYINT(1)          -> SMALLINT with CHECK (IN (0, 1)), not BOOLEAN: the
--                            code compares `is_active = 1` and writes 0/1.
--   * DATETIME/TIMESTAMP  -> TIMESTAMPTZ (one unambiguous point in time; the
--                            code mixes UTC_TIMESTAMP() and JS Dates).
--   * ON UPDATE CURRENT_TIMESTAMP -> the set_updated_at() trigger below.
--   * KEY (...)           -> separate CREATE INDEX statements. InnoDB silently
--                            indexes every foreign key; Postgres does not, so
--                            any FK column without an index got one here.
--   * utf8mb4_unicode_ci  -> Postgres compares case-sensitively. The app
--                            already lowercases emails before storing and
--                            looking them up, so plain UNIQUE (email) matches.

-- ---------------------------------------------------------------------------
-- updated_at maintenance (replaces MySQL's ON UPDATE CURRENT_TIMESTAMP).
-- Like MySQL, it only bumps the timestamp when the row actually changed and
-- the UPDATE didn't set updated_at itself.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
  IF NEW.updated_at IS NOT DISTINCT FROM OLD.updated_at THEN
    NEW.updated_at := CURRENT_TIMESTAMP;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

